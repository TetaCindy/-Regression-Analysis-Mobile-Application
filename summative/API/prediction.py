"""
FastAPI service for the garment-worker productivity model.

Routes
------
POST /predict  -> predicted productivity (0-1) for one production team-day
POST /retrain  -> upload a CSV of new rows; the model is updated in memory
GET  /docs     -> Swagger UI (generated by FastAPI)

Run locally (from summative/API):
    uv run uvicorn prediction:app --reload
"""
import io
import threading
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field
from sklearn.metrics import mean_squared_error

# --------------------------------------------------------------------------
# Load the saved model once, when the server starts.
# best_model.pkl is a dict written by multivariate.ipynb with these keys:
#   pipeline, model_name, features, categorical, numeric, target, data
# --------------------------------------------------------------------------
MODEL_PATH = Path(__file__).resolve().parent / "best_model.pkl"
if not MODEL_PATH.exists():
    raise RuntimeError(
        f"{MODEL_PATH} not found. Run linear_regression/multivariate.ipynb "
        "to train and save the model first."
    )
bundle = joblib.load(MODEL_PATH)
model_lock = threading.Lock()  # one retrain at a time; predictions wait briefly


def clean_df(df: pd.DataFrame) -> pd.DataFrame:
    """Same label cleaning that the notebook applies before training."""
    df = df.copy()
    if "department" in df.columns:
        df["department"] = (
            df["department"].astype(str).str.strip().str.lower().replace({"sweing": "sewing"})
        )
    if "day" in df.columns:
        df["day"] = df["day"].astype(str).str.strip().str.title()
    return df


# --------------------------------------------------------------------------
# Request / response schemas (Pydantic).
# Every field has an enforced type and a realistic range, so a wrong type,
# a missing value or an out-of-range value returns a 422 error, not a prediction.
# Ranges are based on the min/max values seen in the training data.
# --------------------------------------------------------------------------
class PredictionInput(BaseModel):
    department: Literal["sewing", "finishing"] = Field(..., description="Department of the team")
    day: Literal["Monday", "Tuesday", "Wednesday", "Thursday", "Saturday", "Sunday"] = Field(
        ..., description="Day of the week"
    )
    team: int = Field(..., ge=1, le=12, description="Team number (1-12)")
    targeted_productivity: float = Field(..., ge=0.0, le=1.0, description="Target set by management (0-1)")
    smv: float = Field(..., ge=0.0, le=100.0, description="Standard minute value: time allocated per task")
    over_time: int = Field(..., ge=0, le=30000, description="Overtime of the team, in minutes")
    incentive: int = Field(..., ge=0, le=5000, description="Financial incentive (BDT) for the team")
    idle_time: float = Field(..., ge=0.0, le=500.0, description="Minutes production was interrupted")
    idle_men: int = Field(..., ge=0, le=100, description="Number of idle workers due to interruption")
    no_of_style_change: int = Field(..., ge=0, le=5, description="Number of changes in the product style")
    no_of_workers: float = Field(..., ge=1.0, le=100.0, description="Number of workers in the team")

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "department": "sewing",
                "day": "Thursday",
                "team": 8,
                "targeted_productivity": 0.8,
                "smv": 26.16,
                "over_time": 7080,
                "incentive": 98,
                "idle_time": 0,
                "idle_men": 0,
                "no_of_style_change": 0,
                "no_of_workers": 59,
            }
        }
    )


class PredictionOutput(BaseModel):
    predicted_productivity: float
    model: str


app = FastAPI(
    title="Garment Worker Productivity API",
    description="Predicts the actual productivity (0-1) of a garment production team.",
    version="1.0.0",
)

# --------------------------------------------------------------------------
# CORS
# Allowed: only the browser origins listed below (my deployed Render URL and the
#   local addresses I use while developing), only GET and POST, and only the
#   Content-Type / Accept headers that the API really needs.
# Restricted: every other website is blocked from calling this API from a browser,
#   so no random page can use it. No wildcard "*" is used anywhere.
# Credentials are off because the API uses no cookies or login, so there is
#   nothing to protect by sending them.
# Note: the Flutter mobile app is not a browser, so CORS does not apply to it.
#   This setting controls which WEBSITES can call the API.
# --------------------------------------------------------------------------
ALLOWED_ORIGINS = [
    "https://YOUR-SERVICE.onrender.com",  # deployed API (Swagger UI lives here)
    "http://localhost:8000",              # local uvicorn
    "http://127.0.0.1:8000",
    "http://localhost:5000",              # Flutter web debug: flutter run -d chrome --web-port 5000
    "http://127.0.0.1:5000",
]
app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
)


@app.get("/", include_in_schema=False)
def root():
    return {"message": "Garment productivity API. Open /docs for Swagger UI."}


@app.post("/predict", response_model=PredictionOutput)
def predict(item: PredictionInput):
    """Predict actual productivity for one team-day."""
    row = pd.DataFrame([item.model_dump()])[bundle["features"]]
    with model_lock:
        prediction = float(bundle["pipeline"].predict(row)[0])
    return PredictionOutput(predicted_productivity=round(prediction, 4), model=bundle["model_name"])


@app.post("/retrain")
async def retrain(file: UploadFile = File(..., description="CSV with the same columns as the training data")):
    """
    Upload a CSV of new rows. Uploading triggers retraining straight away:
      - SGDRegressor: continue training the saved model on the new rows (partial_fit)
      - any other model: refit on the original data + the new rows
    /predict uses the updated model immediately (no redeploy needed).
    """
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")
    try:
        new_df = pd.read_csv(io.BytesIO(await file.read()))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as a CSV.")

    features, target = bundle["features"], bundle["target"]
    missing = [c for c in features + [target] if c not in new_df.columns]
    if missing:
        raise HTTPException(status_code=422, detail=f"CSV is missing required columns: {missing}")

    new_df = clean_df(new_df)[features + [target]]
    for col in bundle["numeric"] + [target]:
        new_df[col] = pd.to_numeric(new_df[col], errors="coerce")
    n_uploaded = len(new_df)
    new_df = new_df.dropna()
    if new_df.empty:
        raise HTTPException(status_code=422, detail="No valid rows found after cleaning the CSV.")

    with model_lock:
        pipeline = bundle["pipeline"]
        if bundle["model_name"] == "SGDRegressor":
            X_new = pipeline.named_steps["preprocessor"].transform(new_df[features])
            pipeline.named_steps["model"].partial_fit(X_new, new_df[target])
            method = "partial_fit on the new rows"
        else:
            combined = pd.concat([bundle["data"], new_df], ignore_index=True)
            pipeline.fit(combined[features], combined[target])
            method = "refit on original data + new rows"
        bundle["data"] = pd.concat([bundle["data"], new_df], ignore_index=True)
        mse_new = float(mean_squared_error(new_df[target], pipeline.predict(new_df[features])))

    return {
        "message": "Model retrained and now in use.",
        "model": bundle["model_name"],
        "method": method,
        "rows_uploaded": n_uploaded,
        "rows_used": len(new_df),
        "total_rows_known": len(bundle["data"]),
        "mse_on_new_rows": round(mse_new, 5),
    }
