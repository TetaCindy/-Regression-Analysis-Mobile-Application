"""Hospital visit-time API.

POST /predict  -> predicted total minutes a patient will spend in the emergency department
POST /retrain  -> upload a CSV of new visits; the model is updated and used straight away
GET  /docs     -> Swagger UI (generated by FastAPI)
"""
import io
import os
import threading
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import RedirectResponse
from pydantic import BaseModel, Field, ValidationError
from retrain import update_model

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "best_model.pkl"

FEATURES = [
    "age", "sex", "arrival_hour", "day_of_week",
    "arrived_by_ambulance", "urgency", "injury_related", "insurance",
]
TARGET = "visit_minutes"
MAX_AGE_IN_DATA = 94   # the CDC file records every patient aged 94 or older as 94


# ---------------------------------------------------------------- request models
class PatientInput(BaseModel):
    """One patient arriving at the emergency department. Every field is required."""

    # Age 0-120: nobody older is realistic. The training data tops out at 94 ("94 or older"),
    # so ages above 94 are treated as 94 before predicting.
    age: int = Field(ge=0, le=120, strict=True, description="Age in years (0-120)")
    sex: Literal["Female", "Male"]
    # 24-hour clock, the hour the patient arrives
    arrival_hour: int = Field(ge=0, le=23, strict=True, description="Hour of arrival, 0-23")
    day_of_week: Literal["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
    arrived_by_ambulance: Literal["Yes", "No"]
    # Urgency is the triage level a nurse assigns on arrival
    urgency: Literal["Immediate", "Emergent", "Urgent", "Semi-urgent", "Non-urgent"]
    injury_related: Literal["Yes", "No"]
    insurance: Literal["Private", "Medicare", "Medicaid", "Self-pay", "Other"]

    model_config = {
        "json_schema_extra": {
            "example": {
                "age": "46", "sex": "Female", "arrival_hour": 8, "day_of_week": "Tuesday",
                "arrived_by_ambulance": "No", "urgency": "Urgent",
                "injury_related": "No", "insurance": "Private",
            }
        }
    }


class TrainingRow(PatientInput):
    """A row of the retraining CSV: the 8 inputs plus the true visit length."""

    # 1440 minutes = 24 hours; longer stays were removed from the training data
    visit_minutes: int = Field(ge=0, le=1440, description="Total minutes in the ED (0-1440)")


class PredictionOut(BaseModel):
    predicted_visit_minutes: float
    predicted_visit_text: str
    model: str


# ---------------------------------------------------------------- app + CORS
app = FastAPI(
    title="Hospital Visit Time Predictor",
    description="Predicts how long an emergency department visit will take, from details known on arrival.",
    version="1.0.0",
)

# CORS decides which WEBSITES may call this API from a browser.
# Allowed: our own Swagger page (localhost / 127.0.0.1 on port 8000), a Flutter web debug
# server on port 5000, and this service's own public URL (Render sets RENDER_EXTERNAL_URL).
# Restricted: every other website origin; no wildcard "*".
# Methods: only GET (docs) and POST (/predict, /retrain). Headers: only what a JSON/CSV call needs.
# Credentials: False, because the API uses no cookies or logins, so browsers never need to send them.
# The Flutter phone app is not a browser, so CORS does not apply to it at all.
ALLOWED_ORIGINS = [
    "http://localhost:8000",
    "http://127.0.0.1:8000",
    "http://localhost:5000",
    "http://127.0.0.1:5000",
]
if os.environ.get("RENDER_EXTERNAL_URL"):
    ALLOWED_ORIGINS.append(os.environ["RENDER_EXTERNAL_URL"])

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)

# ---------------------------------------------------------------- model + data in memory
_lock = threading.Lock()
MODEL = joblib.load(MODEL_PATH)                 # loaded from the repository at startup

TRAIN_DF = getattr(MODEL, "training_rows_", pd.DataFrame(columns=FEATURES + [TARGET]))


def _model_name(model) -> str:
    return type(model.named_steps["model"]).__name__


def _to_text(minutes: float) -> str:
    total = int(round(minutes))
    hours, mins = divmod(total, 60)
    return f"about {hours} h {mins:02d} min" if hours else f"about {mins} min"


@app.get("/", include_in_schema=False)
def root():
    return RedirectResponse(url="/docs")


# ---------------------------------------------------------------- /predict
@app.post("/predict", response_model=PredictionOut)
def predict(patient: PatientInput):
    row = pd.DataFrame([patient.model_dump()])[FEATURES]
    row["age"] = row["age"].clip(upper=MAX_AGE_IN_DATA)
    with _lock:
        model = MODEL
    minutes = max(0.0, float(model.predict(row)[0]))   # a linear model can dip below zero
    return PredictionOut(
        predicted_visit_minutes=round(minutes, 1),
        predicted_visit_text=_to_text(minutes),
        model=_model_name(model),
    )


# ---------------------------------------------------------------- /retrain
@app.post("/retrain")
async def retrain(file: UploadFile = File(..., description="CSV with the 8 input columns plus visit_minutes")):
    """Upload a CSV of new visits. Uploading is the only trigger; /predict uses the updated model at once."""
    global MODEL, TRAIN_DF

    try:
        new = pd.read_csv(io.BytesIO(await file.read()))
    except Exception:
        raise HTTPException(status_code=422, detail="Could not read the upload as a CSV file.")

    needed = FEATURES + [TARGET]
    missing = [c for c in needed if c not in new.columns]
    if missing:
        raise HTTPException(status_code=422, detail=f"CSV is missing required columns: {missing}")
    if new.empty:
        raise HTTPException(status_code=422, detail="CSV has no rows.")
    new = new[needed]            # extra columns (e.g. month, region) are ignored

    problems = []
    for i, record in enumerate(new.to_dict("records")):
        try:
            TrainingRow(**record)
        except ValidationError as err:
            first = err.errors()[0]
            problems.append(f"row {i + 2}: {first['loc'][0]}: {first['msg']}")
        if len(problems) == 5:
            break
    if problems:
        raise HTTPException(status_code=422, detail={"message": "Invalid rows in CSV (first 5 shown)", "problems": problems})

    new["age"] = new["age"].clip(upper=MAX_AGE_IN_DATA)
    new_X, new_y = new[FEATURES], new[TARGET]

    with _lock:
        current = MODEL
        updated, method, mse_before = update_model(current, new_X, new_y, TRAIN_DF, FEATURES, TARGET)

        TRAIN_DF = pd.concat([TRAIN_DF, new], ignore_index=True)
        MODEL = updated      # /predict now uses the updated model, no redeploy needed

    return {
        "rows_uploaded": int(len(new)),
        "total_rows_known": int(len(TRAIN_DF)),
        "model": _model_name(updated),
        "method": method,
        "mse_on_new_rows_before_update": round(mse_before, 1),
        "note": "The model in memory is updated. On a free Render plan it resets to the saved model when the service restarts.",
    }